-- DataSearcher Demo: ClickHouse events база
-- 2 таблицы: page_views и clicks (аналитика веб-сайта)

CREATE TABLE IF NOT EXISTS page_views (
    event_time DateTime,
    user_id UInt32,
    session_id String,
    page_url String,
    referrer String,
    device_type LowCardinality(String),
    country LowCardinality(String),
    city LowCardinality(String),
    duration_seconds UInt32
) ENGINE = MergeTree()
ORDER BY (event_time, user_id)
PARTITION BY toYYYYMM(event_time);

CREATE TABLE IF NOT EXISTS clicks (
    event_time DateTime,
    user_id UInt32,
    session_id String,
    element_id String,
    page_url String,
    click_x UInt16,
    click_y UInt16
) ENGINE = MergeTree()
ORDER BY (event_time, user_id)
PARTITION BY toYYYYMM(event_time);

